import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {chromium} from '@playwright/test';

const base = process.env.DEBBUILDER_FRONTEND_URL || 'http://127.0.0.1:5181';
const first = {...JSON.parse(readFileSync(new URL('../../tests/fixtures/recipes/seerr.json',import.meta.url))),automation:{enabled:false,policy:'manual'}};
const second = {...first,name:'second-recipe',package:{...first.package,name:'second-recipe'},service:{...first.service,enabled:false,name:'',command:''}};
const recipes = [first,second];
const revision = 'a'.repeat(64);
const browser = await chromium.launch({headless:true});
try {
  const page = await browser.newPage({viewport:{width:1440,height:900}});
  const errors = [];
  const secondaryReads = [];
  page.on('pageerror',error => errors.push(error.message));
  page.on('console',message => {if (message.type() === 'error') errors.push(message.text());});
  await page.route('**/api/**',route => {
    const path = new URL(route.request().url()).pathname;
    if (!path.startsWith('/api/')) return route.continue();
    const respond = (body,headers={}) => route.fulfill({status:200,contentType:'application/json',headers,body:JSON.stringify(body)});
    if (path === '/api/auth/status') return respond({ok:true,auth_mode:'local'});
    if (path === '/api/status') return respond({ok:true});
    if (path === '/api/recipes') return respond({recipes:recipes.map(recipe => ({id:recipe.name,package:recipe.package.name,repository:recipe.source.repository}))});
    if (path === '/api/workflows') return respond({workflows:recipes.map(recipe => ({id:recipe.name,writable:true})),errors:[]});
    if (path.endsWith('/inspect') || path.endsWith('/automation')) secondaryReads.push(path);
    const recipe = recipes.find(item => path === `/api/workflows/${item.name}`);
    if (recipe) return respond(recipe,{ETag:`"${revision}"`});
    return route.fulfill({status:404,contentType:'application/json',body:JSON.stringify({error:{code:'unexpected_read',message:path}})});
  });

  await page.goto(`${base}/#/recipes`);
  try {await page.locator('.recipe-editor').getByRole('heading',{name:'seerr'}).waitFor({timeout:5000});}
  catch (error) {console.error(errors,await page.content()); throw error;}
  assert.equal(await page.locator('.recipe-picker .selected').count(),1);
  assert.equal(await page.locator('.recipe-picker .selected strong').innerText(),'seerr');
  assert.equal(await page.locator('.recipe-identity .identity-actions').count(),0);
  assert.equal(await page.locator('.recipe-savebar').count(),0);
  await page.getByRole('button',{name:'Customize',exact:true}).click();
  assert.equal(await page.locator('.recipe-savebar').count(),0);
  assert.equal(await page.locator('.recipe-task-group[open]').count(),0);
  assert.equal(await page.locator('[data-recipe-path="active"]').count(),1);
  assert.equal(await page.locator('[data-recipe-path="package.name"]').count(),1);
  assert.equal(await page.locator('[data-recipe-path="automation.policy"]').count(),1);
  assert.equal(await page.locator('[data-recipe-path="automation.enabled"]').count(),0);
  const automationGroup = page.locator('.recipe-task-group').filter({hasText:'Automation'}).first();
  await automationGroup.locator('summary').click();
  const automation = page.locator('[data-recipe-path="automation.policy"] select');
  assert.equal(await automation.locator('option[value="manual"]').innerText(),'Disabled');
  await automation.selectOption('detect');
  await page.getByRole('button',{name:'Expert',exact:true}).click();
  const automationDraft = JSON.parse(await page.locator('.recipe-json pre').textContent());
  assert.deepEqual(automationDraft.automation,{enabled:true,policy:'detect'});
  await page.getByRole('button',{name:'Customize',exact:true}).click();
  await automationGroup.locator('summary').click();
  await automation.selectOption('manual');
  assert.equal(await page.locator('.recipe-savebar').count(),0);
  await page.getByRole('button',{name:'Plan',exact:true}).click();
  assert.equal(await page.locator('.recipe-plan').count(),1);
  assert.equal(await page.locator('.recipe-savebar').count(),0);
  assert.equal(await page.locator('.recipe-identity .identity-actions').count(),0);
  await page.getByRole('button',{name:'Customize',exact:true}).click();
  assert.equal(await page.locator('.recipe-task-group[open]').count(),0);
  await page.locator('.recipe-task-group').filter({hasText:'Package metadata'}).first().locator('summary').click();
  const description = page.locator('[data-recipe-path="package.description"] textarea');
  await description.fill(`${await description.inputValue()} pending`);
  await page.locator('.recipe-savebar').waitFor();
  await page.getByRole('button',{name:'Plan',exact:true}).click();
  assert.equal(await page.locator('.recipe-savebar').count(),1);
  assert.equal(await page.locator('.recipe-plan').count(),1);
  assert.equal(await page.locator('[data-recipe-path="package.description"]').count(),0);
  await page.getByRole('button',{name:'Customize',exact:true}).click();
  await page.locator('.recipe-task-group').filter({hasText:'Package metadata'}).first().locator('summary').click();
  assert.match(await description.inputValue(),/ pending$/);
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  assert.equal(await page.locator('.recipe-plan').count(),1);
  assert.equal(await page.locator('.recipe-savebar').count(),0);
  assert.equal(await page.locator('.recipe-inspection,.recipe-automation').count(),0);
  await page.getByRole('button',{name:'Advanced',exact:true}).click();
  assert.equal(await page.locator('.recipe-task-group[open]').count(),0);
  await page.getByRole('button',{name:'Expert',exact:true}).click();
  assert.equal(await page.locator('.recipe-task-group[open]').count(),0);
  assert.equal(await page.locator('.recipe-inspection,.recipe-automation').count(),0);
  assert.equal(await page.locator('.recipe-json').count(),1);
  await page.getByRole('button',{name:'Plan',exact:true}).click();
  assert.equal(await page.locator('.recipe-inspection,.recipe-automation').count(),0);
  await page.locator('.recipe-picker').getByRole('button',{name:/second-recipe/}).click();
  await page.locator('.recipe-editor').getByRole('heading',{name:'second-recipe'}).waitFor();
  await page.goto(`${base}/#/recipes`);
  await page.locator('.recipe-editor').getByRole('heading',{name:'seerr'}).waitFor();
  assert.deepEqual(secondaryReads,[]);
  await page.evaluate(() => localStorage.setItem('debBuilder24Locale','fr'));
  await page.reload();
  await page.locator('.recipe-editor').getByRole('heading',{name:'seerr'}).waitFor();
  await page.getByRole('button',{name:'Personnaliser',exact:true}).click();
  await page.locator('.recipe-task-group').filter({hasText:'Source'}).first().locator('summary').click();
  const tracking = page.locator('[data-recipe-path="source.tracking"] select');
  assert.equal(await tracking.locator('option[value="latest_release"]').innerText(),'Dernière version publiée');
  await tracking.selectOption('manual');
  await page.getByRole('button',{name:'Vérifier les changements'}).first().click();
  assert.equal(await page.locator('.recipe-review-head').getByText('Enregistré',{exact:true}).count(),1);
  assert.equal(await page.locator('.recipe-review-head').getByText('Vos modifications',{exact:true}).count(),1);
  assert.equal(await page.locator('.recipe-change-name').getByText('Suivi des versions',{exact:true}).count(),1);
  assert.match(await page.locator('.recipe-review-facts').innerText(),/Dernière version publiée[\s\S]*Référence manuelle/);
  assert.equal(await page.locator('.recipe-review-facts').getByText('$.source.tracking',{exact:true}).count(),0);
  await page.getByRole('button',{name:'Annuler',exact:true}).click();
  await page.goto(`${base}/#/recipes/second-recipe`);
  await page.locator('.recipe-editor').getByRole('heading',{name:'second-recipe'}).waitFor();
  await page.getByRole('button',{name:'Personnaliser',exact:true}).click();
  const serviceGroup = page.locator('[data-recipe-path="service.enabled"]').locator('xpath=ancestor::details[1]');
  await serviceGroup.locator('summary').click();
  await page.locator('[data-recipe-path="service.enabled"] input').check();
  const checkedServices = [];
  const validateService = route => {
    const service = JSON.parse(route.request().postData()).recipe.service;
    checkedServices.push(service);
    const invalid = service.enabled && (!service.name?.trim() || !service.command?.trim()) || service.name && !/^[A-Za-z0-9_.@-]+\.service$/.test(service.name);
    return route.fulfill({status:invalid ? 422 : 200,contentType:'application/json',body:JSON.stringify(invalid ? {ok:false,error:{code:'invalid_recipe',message:'The Recipe is invalid',details:{path:'$'}}} : {ok:true})});
  };
  await page.route('**/api/recipes/validate',validateService);
  await page.getByRole('button',{name:'Valider',exact:true}).click();
  const validationAlert = page.locator('.recipe-main > .notice.error');
  await validationAlert.getByText('Pour activer le service, renseignez son nom et sa commande.').waitFor();
  assert.equal(await validationAlert.getByText('Nom du service',{exact:true}).count(),1);
  assert.equal(await page.locator('[data-recipe-path="service.name"] input').evaluate(node => node === document.activeElement),true);
  assert.equal((await validationAlert.innerText()).includes('global'),false);
  assert.equal((await validationAlert.innerText()).includes('The Recipe is invalid'),false);
  const name = page.locator('[data-recipe-path="service.name"] input');
  await name.press('a');
  await name.press('h');
  assert.equal(await name.inputValue(),'ah');
  assert.equal(await name.evaluate(node => node === document.activeElement),true);
  assert.equal(await serviceGroup.evaluate(node => node.open),true);
  await name.fill('ahahah');
  await page.locator('[data-recipe-path="service.command"] input').fill('ca');
  assert.equal(await name.inputValue(),'ahahah.service');
  await page.locator('[data-recipe-path="service.enabled"] input').uncheck();
  await page.getByText('La désactivation conserve le nom et la commande du service dans cette recette.').waitFor();
  await page.getByRole('button',{name:'Valider',exact:true}).click();
  await page.getByText('Modifications valides').waitFor();
  assert.equal(await page.locator('.recipe-savebar .recipe-validation-success').count(),1);
  assert.equal(await page.locator('.recipe-editor .notice:not(.error)').count(),0);
  assert.equal(checkedServices.at(-1).enabled,false);
  assert.equal(checkedServices.at(-1).name,'ahahah.service');
  assert.equal(checkedServices.at(-1).command,'ca');
  await page.locator('[data-recipe-path="service.enabled"] input').check();
  await page.getByRole('button',{name:'Valider',exact:true}).click();
  await page.getByText('Modifications valides').waitFor();
  assert.equal(checkedServices.at(-1).enabled,true);
  await name.fill('bad/name');
  await page.locator('[data-recipe-path="service.enabled"] input').uncheck();
  await page.getByRole('button',{name:'Valider',exact:true}).click();
  await validationAlert.getByText('Saisissez un nom de service valide terminé par .service').waitFor();
  assert.equal(await validationAlert.getByText('Nom du service',{exact:true}).count(),1);
  await page.unroute('**/api/recipes/validate',validateService);
  assert.deepEqual(errors.filter(message => !message.includes('422 (Unprocessable Entity)')),[]);
  console.log('Recipe default and explicit selection checks passed');
} finally {await browser.close();}
